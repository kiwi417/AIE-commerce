-- ----------------------------
-- 1、商城商品分类表
-- ----------------------------
drop table if exists mall_category;
create table mall_category (
  category_id   bigint(20)   not null auto_increment comment '分类id',
  category_name varchar(50)  not null                comment '分类名称',
  sort_order    int(11)      default 0               comment '排序',
  status        char(1)      default '0'             comment '状态（0正常 1停用）',
  create_by     varchar(64)  default ''              comment '创建者',
  create_time   datetime                             comment '创建时间',
  update_by     varchar(64)  default ''              comment '更新者',
  update_time   datetime                             comment '更新时间',
  remark        varchar(500) default null            comment '备注',
  primary key (category_id)
) engine=innodb auto_increment=1 default charset=utf8mb4 comment='商城商品分类表';

-- ----------------------------
-- 2、商城商品表
-- ----------------------------
drop table if exists mall_product;
create table mall_product (
  product_id   bigint(20)     not null auto_increment comment '商品id',
  category_id  bigint(20)     not null                comment '分类id',
  product_name varchar(200)   not null                comment '商品名称',
  price        decimal(10,2)  not null                comment '价格',
  stock        int(11)        not null default 0      comment '库存',
  unit         varchar(20)    default ''              comment '单位（件/瓶/盒/包等）',
  barcode      varchar(32)    default ''              comment '条码',
  shelf_area   varchar(50)    default ''              comment '货架位置',
  description  varchar(1000)  default ''              comment '商品描述',
  tags         varchar(500)   default ''              comment '标签（逗号分隔，检索与展示）',
  image_url    varchar(255)   default ''              comment '图片地址（本期为空，前端显示首字占位）',
  status       char(1)        default '0'             comment '状态（0上架 1下架）',
  create_by    varchar(64)    default ''              comment '创建者',
  create_time  datetime                               comment '创建时间',
  update_by    varchar(64)    default ''              comment '更新者',
  update_time  datetime                               comment '更新时间',
  remark       varchar(500)   default null            comment '备注',
  primary key (product_id),
  key idx_category_status (category_id, status)
) engine=innodb auto_increment=1 default charset=utf8mb4 comment='商城商品表';

